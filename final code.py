# --- FUNCTION 1: Predict price from specs ---
def predict_price(brand, cpu_brand, cpu_gen, cpu_cores, cpu_threads, ram, storage,
                  ssd, hdd, vram, battery, os, screen, ppi, touch):
    input_data = [[brand, cpu_brand, cpu_gen, cpu_cores, cpu_threads,
                   ram, storage, ssd, hdd, vram, battery, os, screen, ppi, touch]]
    try:
        price = int(pipe.predict(input_data)[0])
        return f"💰 Estimated Price: ₹{price}"
    except Exception as e:
        return f"❌ Prediction Error: {str(e)}"

# --- FUNCTION 2: Filter laptops by price range ---
def filter_by_price_range(min_price, max_price):
    try:
        result = df[(df['price(in rupees)'] >= min_price) & (df['price(in rupees)'] <= max_price)]
        if result.empty:
            return "❌ No laptops found in this range."
        return result[['brand', 'cpu_model', 'price(in rupees)']].sort_values(by='price(in rupees)').to_string(index=False)
    except Exception as e:
        return f"❌ Error: {str(e)}"

# --- FUNCTION 3: Filter laptops by brand and price ---
def laptops_by_price_brand(price, brand):
    try:
        result = df[(df['price(in rupees)'] <= price) & (df['brand'] == brand)]
        if result.empty:
            return "❌ No laptops found for this brand within price."
        return result[['brand', 'cpu_model', 'price(in rupees)']].sort_values(by='price(in rupees)').to_markdown(index=False)
    except Exception as e:
        return f"❌ Error: {str(e)}"

