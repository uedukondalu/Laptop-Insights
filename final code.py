def find_ranges(num):
    str_num = str(num)
    first_digit = int(str_num[0])
    length = len(str_num)

    lowest_range = first_digit * (10 ** (length - 1))

    highest_range = (first_digit + 1) * (10 ** (length - 1))

    return lowest_range, highest_range

